def load_yolo_labels(label_path, img_size=640):
    """Load YOLO format labels and convert to pixel coordinates"""
    boxes = []
    labels = []

    if not os.path.exists(label_path):
        return torch.zeros((0, 4)), torch.zeros((0,), dtype=torch.int64)

    with open(label_path, 'r') as f:
        for line in f:
            parts = line.strip().split()
            if len(parts) < 5:
                continue
            cls = int(parts[0]) + 1  # label_offset = 1
            cx, cy, w, h = map(float, parts[1:5])

            # Convert normalized to pixel
            x1 = (cx - w/2) * img_size
            y1 = (cy - h/2) * img_size
            x2 = (cx + w/2) * img_size
            y2 = (cy + h/2) * img_size

            boxes.append([x1, y1, x2, y2])
            labels.append(cls)

    if len(boxes) == 0:
        return torch.zeros((0, 4)), torch.zeros((0,), dtype=torch.int64)

    return torch.tensor(boxes, dtype=torch.float32), torch.tensor(labels, dtype=torch.int64)


def compute_iou(box1, box2):
    """Compute IoU between two boxes"""
    x1 = max(box1[0], box2[0])
    y1 = max(box1[1], box2[1])
    x2 = min(box1[2], box2[2])
    y2 = min(box1[3], box2[3])

    inter = max(0, x2 - x1) * max(0, y2 - y1)
    area1 = (box1[2] - box1[0]) * (box1[3] - box1[1])
    area2 = (box2[2] - box2[0]) * (box2[3] - box2[1])
    union = area1 + area2 - inter

    return inter / union if union > 0 else 0


def compute_ap(predictions, ground_truths, iou_threshold=0.5):
    """Compute Average Precision at given IoU threshold"""
    all_preds = []
    all_gts = {i: gt for i, gt in enumerate(ground_truths)}
    gt_matched = {i: [False] * len(gt['boxes']) for i, gt in enumerate(ground_truths)}

    for img_idx, pred in enumerate(predictions):
        for box_idx in range(len(pred['boxes'])):
            all_preds.append({
                'img_idx': img_idx,
                'box': pred['boxes'][box_idx],
                'score': pred['scores'][box_idx],
                'label': pred['labels'][box_idx]
            })

    all_preds.sort(key=lambda x: x['score'], reverse=True)

    total_gt = sum(len(gt['boxes']) for gt in ground_truths)
    if total_gt == 0:
        return 0.0

    tp = 0
    fp = 0
    precisions = []
    recalls = []

    for pred in all_preds:
        img_idx = pred['img_idx']
        pred_box = pred['box']
        pred_label = pred['label']

        gt = all_gts[img_idx]
        best_iou = 0
        best_gt_idx = -1

        for gt_idx, (gt_box, gt_label) in enumerate(zip(gt['boxes'], gt['labels'])):
            if gt_matched[img_idx][gt_idx]:
                continue
            if gt_label != pred_label:
                continue
            iou = compute_iou(pred_box, gt_box)
            if iou > best_iou:
                best_iou = iou
                best_gt_idx = gt_idx

        if best_iou >= iou_threshold and best_gt_idx >= 0:
            tp += 1
            gt_matched[img_idx][best_gt_idx] = True
        else:
            fp += 1

        precision = tp / (tp + fp)
        recall = tp / total_gt
        precisions.append(precision)
        recalls.append(recall)

    ap = 0
    for t in np.arange(0, 1.1, 0.1):
        p = max([p for p, r in zip(precisions, recalls) if r >= t], default=0)
        ap += p / 11

    return ap


def evaluate_with_sr(sr_model, detector, lr_dir, hr_dir, label_dir, device, score_thresh=0.3):
    """Evaluate detector on SR images generated by SR model"""
    sr_model.eval()
    detector.eval()

    predictions_sr = []
    predictions_hr = []
    ground_truths = []

    # Get LR image files
    image_files = sorted([f for f in os.listdir(lr_dir) if f.endswith('.png')])

    print(f"Evaluating on {len(image_files)} images")
    print(f"LR dir: {lr_dir}")
    print(f"HR dir: {hr_dir}")

    for img_file in tqdm(image_files):
        # Load LR image (80x80)
        lr_path = os.path.join(lr_dir, img_file)
        lr_img = Image.open(lr_path).convert('L')
        lr_tensor = torch.from_numpy(np.array(lr_img)).float() / 255.0
        lr_tensor = lr_tensor.unsqueeze(0).unsqueeze(0).to(device)  # [1, 1, 80, 80]

        # Load HR image (640x640)
        hr_path = os.path.join(hr_dir, img_file)
        hr_img = Image.open(hr_path).convert('L')
        hr_tensor = torch.from_numpy(np.array(hr_img)).float() / 255.0
        hr_tensor = hr_tensor.unsqueeze(0).unsqueeze(0).to(device)  # [1, 1, 640, 640]

        img_size = 640

        # Load labels
        label_file = img_file.replace('.png', '.txt')
        label_path = os.path.join(label_dir, label_file)
        gt_boxes, gt_labels = load_yolo_labels(label_path, img_size)

        ground_truths.append({
            'boxes': gt_boxes.numpy(),
            'labels': gt_labels.numpy()
        })

        with torch.no_grad():
            # Generate SR image
            # ★ SonarSR expects [-1, 1] input, outputs [-1, 1]
            lr_tensor_norm = 2 * lr_tensor - 1  # [0,1] → [-1,1]
            sr_tensor, _ = sr_model(lr_tensor_norm)  # [1, 1, 640, 640]
            sr_tensor = ((sr_tensor + 1) / 2).clamp(0, 1)  # [-1,1] → [0,1]

            # Run detection on SR
            img_list_sr = [sr_tensor[0]]
            outputs_sr, _ = detector(img_list_sr)
            output_sr = outputs_sr[0]
            keep_sr = output_sr['scores'] >= score_thresh

            predictions_sr.append({
                'boxes': output_sr['boxes'][keep_sr].cpu().numpy(),
                'scores': output_sr['scores'][keep_sr].cpu().numpy(),
                'labels': output_sr['labels'][keep_sr].cpu().numpy()
            })

            # Run detection on HR
            img_list_hr = [hr_tensor[0]]
            outputs_hr, _ = detector(img_list_hr)
            output_hr = outputs_hr[0]
            keep_hr = output_hr['scores'] >= score_thresh

            predictions_hr.append({
                'boxes': output_hr['boxes'][keep_hr].cpu().numpy(),
                'scores': output_hr['scores'][keep_hr].cpu().numpy(),
                'labels': output_hr['labels'][keep_hr].cpu().numpy()
            })

    # Compute mAP for SR
    ap50_sr = compute_ap(predictions_sr, ground_truths, iou_threshold=0.5)
    ap25_sr = compute_ap(predictions_sr, ground_truths, iou_threshold=0.25)
    ap75_sr = compute_ap(predictions_sr, ground_truths, iou_threshold=0.75)

    # Compute mAP for HR
    ap50_hr = compute_ap(predictions_hr, ground_truths, iou_threshold=0.5)
    ap25_hr = compute_ap(predictions_hr, ground_truths, iou_threshold=0.25)
    ap75_hr = compute_ap(predictions_hr, ground_truths, iou_threshold=0.75)

    return {
        'SR': {'mAP@25': ap25_sr, 'mAP@50': ap50_sr, 'mAP@75': ap75_sr},
        'HR': {'mAP@25': ap25_hr, 'mAP@50': ap50_hr, 'mAP@75': ap75_hr},
        'num_images': len(image_files)
    }


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument('--lr_dir', type=str,
                        default='/mnt/server16_hard0/kangwook/LIGNex1/SonarSR/eval/test_focus/noisy_bilinear_0.2_0.5')
    parser.add_argument('--hr_dir', type=str,
                        default='/mnt/server16_hard0/kangwook/LIGNex1/SonarSR/eval/test_focus/hr')
    parser.add_argument('--label_dir', type=str,
                        default='/mnt/server16_hard1/LIGNEX1/yolo_data/combined/test/labels')
    parser.add_argument('--sr_weights', type=str,
                        default='/mnt/server16_hard0/kangwook/LIGNex1/SonarSR/checkpoints/sr_arch_pixelshuffle_globalo_v2/model_step_100000.pth')
    parser.add_argument('--detector_weights', type=str,
                        default='/mnt/server16_hard1/LIGNEX1/SR4IR/runs_det_pure1ch_pretrained/best_map.pth')
    parser.add_argument('--score_thresh', type=float, default=0.3)
    args = parser.parse_args()

    device = torch.device('cuda' if torch.cuda.is_available() else 'cpu')
    print(f"Using device: {device}")

    # Build SR model
    print("Loading SR model (sr_arch_pixelshuffle_globalo_v2)...")
    sr_model = build_sr(
        in_channels=1,
        num_residual_blocks=8,
        base_channels=64,
        scale=8
    )

    # Load SR weights
    sr_state_dict = torch.load(args.sr_weights, map_location='cpu')
    # Check if nested under 'generator_state_dict'
    if 'generator_state_dict' in sr_state_dict:
        sr_state_dict = sr_state_dict['generator_state_dict']
    sr_model.load_state_dict(sr_state_dict, strict=True)
    sr_model = sr_model.to(device)
    print(f"Loaded SR weights from {args.sr_weights}")

    # Build detector
    print("Loading detector...")
    detector = build_detector(
        use_1ch=True,
        backbone_variant='large',
        num_classes=3,
        image_mean=[0.449],
        image_std=[0.226]
    )

    # Load detector weights
    det_state_dict = torch.load(args.detector_weights, map_location='cpu')
    detector.load_state_dict(det_state_dict, strict=True)
    detector = detector.to(device)
    print(f"Loaded detector weights from {args.detector_weights}")

    # Evaluate
    print("\n" + "="*60)
    print("Evaluating detector on SR images from sr_arch_pixelshuffle_globalo_v2")
    print("="*60)

    results = evaluate_with_sr(
        sr_model, detector,
        args.lr_dir, args.hr_dir, args.label_dir,
        device, args.score_thresh
    )

    # Print results
    print("\n" + "="*60)
    print("Results")
    print("="*60)
    print(f"{'Metric':<10} {'HR':<12} {'SR (pixelshuffle)':<12} {'Gap':<10}")
    print("-"*50)
    print(f"{'mAP@25':<10} {results['HR']['mAP@25']:<12.4f} {results['SR']['mAP@25']:<12.4f} {results['HR']['mAP@25'] - results['SR']['mAP@25']:<10.4f}")
    print(f"{'mAP@50':<10} {results['HR']['mAP@50']:<12.4f} {results['SR']['mAP@50']:<12.4f} {results['HR']['mAP@50'] - results['SR']['mAP@50']:<10.4f}")
    print(f"{'mAP@75':<10} {results['HR']['mAP@75']:<12.4f} {results['SR']['mAP@75']:<12.4f} {results['HR']['mAP@75'] - results['SR']['mAP@75']:<10.4f}")

    print("\n" + "="*60)
    print("This is the BASELINE for SR4IR training!")
    print("SR4IR should improve SR mAP towards HR mAP through joint training.")
    print("="*60)


if __name__ == '__main__':
    main()
